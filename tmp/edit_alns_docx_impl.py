def paragraph_text(paragraph: Paragraph) -> str:
    return paragraph.text.strip().replace("\u3000", " ")


def clear_paragraph(paragraph: Paragraph) -> None:
    p = paragraph._element
    for child in list(p):
        p.remove(child)


def set_paragraph_text(paragraph: Paragraph, text: str) -> None:
    clear_paragraph(paragraph)
    if text:
        paragraph.add_run(text)


def insert_paragraph_after(paragraph: Paragraph, text: str = "") -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if paragraph.style is not None:
        new_para.style = paragraph.style
    if text:
        new_para.add_run(text)
    return new_para


def find_index(paragraphs: list[Paragraph], needle: str) -> int:
    for i, p in enumerate(paragraphs):
        if paragraph_text(p) == needle:
            return i
    raise ValueError(f"Paragraph not found: {needle}")


def find_index_contains(paragraphs: list[Paragraph], needle: str) -> int:
    for i, p in enumerate(paragraphs):
        if needle in paragraph_text(p):
            return i
    raise ValueError(f"Paragraph containing text not found: {needle}")


def clone_paragraph_after(anchor: Paragraph, source: Paragraph) -> Paragraph:
    new_elem = deepcopy(source._element)
    anchor._p.addnext(new_elem)
    return Paragraph(new_elem, anchor._parent)


def validate_docx(path: str) -> dict[str, int | bool]:
    with zipfile.ZipFile(path) as zf:
        xml = zf.read("word/document.xml").decode("utf-8")
    return {
        "omath_count": xml.count("<m:oMath") + xml.count("<m:oMathPara"),
        "has_raw_latex": "\\" in xml,
        "paragraph_count": xml.count("<w:p"),
    }


